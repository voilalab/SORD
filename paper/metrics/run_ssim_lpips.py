"""Score every registered (table, bench, arm) with PSNR / SSIM / LPIPS and write
paper/metrics/ssim_lpips.json, ssim_lpips.md and tables/ssim_lpips_<table>.tex.
  CUDA_VISIBLE_DEVICES=g ~/miniconda3/envs/joint-diffusion/bin/python paper/metrics/run_ssim_lpips.py [--table faces,wm,shadow] [--net alex]
Results are cached per entry in ssim_lpips.json; --redo forces recompute."""
import sys, json, argparse, importlib, traceback, time
from pathlib import Path
REPO = next(p for p in Path(__file__).resolve().parents if (p / "sord").is_dir()); sys.path.insert(0, str(REPO)); sys.path.insert(0, str(REPO / "paper/metrics"))
import ssim_lpips_core as C

ap = argparse.ArgumentParser(); ap.add_argument("--table", default="faces,wm,shadow"); ap.add_argument("--redo", action="store_true")
ap.add_argument("--only", default=None, help="substring filter on 'bench/arm'")
a = ap.parse_args()
OUT = REPO / "paper/metrics"; J = OUT / "ssim_lpips.json"
res = json.loads(J.read_text()) if J.exists() else {}
for t in a.table.split(","):
    try: mod = importlib.import_module(f"arms_{t}")
    except Exception: print(f"[skip] arms_{t}: {traceback.format_exc().splitlines()[-1]}"); continue
    for e in mod.ENTRIES:
        key = f"{e['table']}|{e['bench']}|{e['arm']}"
        if a.only and a.only not in key: continue
        if key in res and not a.redo and "error" not in res[key]: continue
        t0 = time.time()
        try:
            d = e["loader"](); r = C.score(d); r["note"] = e.get("note", "")
        except Exception as ex:
            r = dict(error=traceback.format_exc().splitlines()[-1]); print(f"[ERR] {key}: {r['error']}")
        res[key] = r; J.write_text(json.dumps(res, indent=1))
        if "error" not in r:
            print(f"{key:60s} n={r['n']:3d} psnr {r['psnr_om_mean']:6.2f} (ref {r.get('psnr_ref', float('nan')):6.2f}) "
                  f"ssim {r['ssim_full_mean']:.3f}/{r['ssim_box_mean']:.3f} lpips {r['lpips_full_mean']:.3f}/{r['lpips_box_mean']:.3f}  [{time.time()-t0:.0f}s]")

# ---- write markdown + latex -------------------------------------------------------------------------
md = ["# SSIM / LPIPS for the paper result tables", "",
      "Per arm: on-Omega PSNR mean/worst (reproduces the paper table; `ref` = table value), SSIM full-frame mean/worst,",
      "LPIPS(alex) full-frame mean/worst, SSIM and LPIPS on the padded mask bounding box (local variant). DPS-family",
      "arms are pasted back to y off-Omega before scoring (raw samples are not exact there). Generated by",
      "paper/metrics/run_ssim_lpips.py; per-entry numbers in ssim_lpips.json.", ""]
tables = {}
for key, r in res.items():
    t, b, arm = key.split("|"); tables.setdefault(t, {}).setdefault(b, []).append((arm, r))
for t, benches in tables.items():
    md += [f"## table: {t}", ""]
    tex = ["\\begin{tabular}{llcccccc}", "\\toprule", "bench & arm & PSNR$_\\Omega$ & SSIM & LPIPS$\\downarrow$ & SSIM$_{\\rm box}$ & LPIPS$_{\\rm box}\\downarrow$ & $n$\\\\", "\\midrule"]
    for b, rows in benches.items():
        md += [f"### {b}", "", "| arm | PSNR_Ω mean/worst (ref) | SSIM full | LPIPS full | SSIM box | LPIPS box | n |", "|---|---|---|---|---|---|---|"]
        for arm, r in rows:
            if "error" in r: md.append(f"| {arm} | ERROR: {r['error']} | | | | | |"); continue
            ref = f" ({r['psnr_ref']:.2f})" if "psnr_ref" in r else ""
            md.append(f"| {arm} | {r['psnr_om_mean']:.2f} / {r['psnr_om_worst']:.2f}{ref} | {r['ssim_full_mean']:.3f} / {r['ssim_full_worst']:.3f} | "
                      f"{r['lpips_full_mean']:.3f} / {r['lpips_full_worst']:.3f} | {r['ssim_box_mean']:.3f} / {r['ssim_box_worst']:.3f} | "
                      f"{r['lpips_box_mean']:.3f} / {r['lpips_box_worst']:.3f} | {r['n']} |")
            tex.append(f"{b} & {arm.replace('_', ' ')} & {r['psnr_om_mean']:.2f} / {r['psnr_om_worst']:.2f} & {r['ssim_full_mean']:.3f} & {r['lpips_full_mean']:.3f} & {r['ssim_box_mean']:.3f} & {r['lpips_box_mean']:.3f} & {r['n']}\\\\")
        md.append(""); tex.append("\\midrule")
    tex[-1] = "\\bottomrule"; tex.append("\\end{tabular}")
    (REPO / "paper/tables" / f"ssim_lpips_{t}.tex").write_text("\n".join(tex) + "\n")
(OUT / "ssim_lpips.md").write_text("\n".join(md) + "\n"); print("wrote", OUT / "ssim_lpips.md")
