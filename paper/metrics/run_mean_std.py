"""Mean +- std (per-image, over the bench) of on-Omega PSNR and full-frame SSIM for every registered
(table, bench, arm) of the paper result tables (same registry as run_ssim_lpips.py: arms_faces / arms_wm / arms_shadow).
  ~/miniconda3/envs/joint-diffusion/bin/python paper/metrics/run_mean_std.py [--table faces,wm,shadow] [--no-ssim]
Writes paper/metrics/mean_std.json, mean_std.md and paper/tables/mean_std_<table>.tex.  CPU only.
std = sample std (ddof=1) over the n images; sem = std/sqrt(n) also stored in the json."""
import sys, json, argparse, importlib, traceback, time
from pathlib import Path
import numpy as np
REPO = next(p for p in Path(__file__).resolve().parents if (p / "sord").is_dir()); sys.path.insert(0, str(REPO)); sys.path.insert(0, str(REPO / "paper/metrics"))

ap = argparse.ArgumentParser(); ap.add_argument("--table", default="faces,wm,shadow"); ap.add_argument("--redo", action="store_true")
ap.add_argument("--no-ssim", action="store_true"); ap.add_argument("--only", default=None)
a = ap.parse_args()
OUT = REPO / "paper/metrics"; J = OUT / "mean_std.json"
res = json.loads(J.read_text()) if J.exists() else {}

def psnr_om(x, g, m):
    e = ((x - g) ** 2)[m > 0.5].mean(); return 10 * np.log10(1 / max(e, 1e-20))

def score(d, do_ssim=True):
    gt = np.clip(np.asarray(d["gt"], np.float32), 0, 1); x = np.clip(np.asarray(d["x"], np.float32), 0, 1)
    y = np.clip(np.asarray(d["y"], np.float32), 0, 1); M = np.asarray(d["M"], np.float32)
    if M.ndim == 3: M = M[..., None]
    if M.shape[-1] == 1: M = np.repeat(M, 3, -1)
    if gt.shape[-1] == 1: gt = np.repeat(gt, 3, -1); x = np.repeat(x, 3, -1); y = np.repeat(y, 3, -1)
    if d.get("project", False): x = np.where(M > 0.5, x, y).astype(np.float32)
    N = len(gt)
    ps = np.array([psnr_om(x[i], gt[i], M[i]) for i in range(N)])
    r = dict(n=int(N), psnr_mean=float(ps.mean()), psnr_std=float(ps.std(ddof=1)), psnr_sem=float(ps.std(ddof=1) / np.sqrt(N)),
             psnr_median=float(np.median(ps)), psnr_min=float(ps.min()), psnr_max=float(ps.max()))
    if do_ssim:
        from skimage.metrics import structural_similarity as ssim_fn
        ss = np.array([ssim_fn(gt[i], x[i], data_range=1.0, channel_axis=-1) for i in range(N)])
        r.update(ssim_mean=float(ss.mean()), ssim_std=float(ss.std(ddof=1)), ssim_sem=float(ss.std(ddof=1) / np.sqrt(N)))
    if d.get("psnr_ref") is not None:
        r["psnr_ref"] = float(d["psnr_ref"]); r["psnr_delta_vs_table"] = float(ps.mean() - d["psnr_ref"])
    return r

for t in a.table.split(","):
    try: mod = importlib.import_module(f"arms_{t}")
    except Exception: print(f"[skip] arms_{t}: {traceback.format_exc().splitlines()[-1]}"); continue
    for e in mod.ENTRIES:
        key = f"{e['table']}|{e['bench']}|{e['arm']}"
        if a.only and a.only not in key: continue
        if key in res and not a.redo and "error" not in res[key]: continue
        t0 = time.time()
        try:
            r = score(e["loader"](), not a.no_ssim); r["note"] = e.get("note", "")
        except Exception:
            r = dict(error=traceback.format_exc().splitlines()[-1]); print(f"[ERR] {key}: {r['error']}")
        res[key] = r
        if "error" not in r:
            ref = r.get("psnr_ref"); flag = "" if ref is None or abs(r["psnr_delta_vs_table"]) <= 0.1 else "  <-- MISMATCH"
            ss = "" if a.no_ssim else f"  ssim {r['ssim_mean']:.3f} +- {r['ssim_std']:.3f}"
            print(f"{key:75s} n={r['n']:3d} psnr {r['psnr_mean']:6.2f} +- {r['psnr_std']:5.2f} (ref {'' if ref is None else f'{ref:.2f}'}){ss}  [{time.time()-t0:.0f}s]{flag}")

try: J.write_text(json.dumps(res, indent=1))
except OSError as ex: print(f"[WARN] json not written: {ex}")
# ---- markdown + latex --------------------------------------------------------------------------------
md = ["# Mean +- std for the paper result tables", "",
      "Per arm: on-Omega PSNR mean +- std (sample std over the n images of the bench; `ref` = the paper table mean),",
      "median, and full-frame SSIM mean +- std. DPS-family arms are pasted back to y off-Omega before scoring.",
      "Generated by paper/metrics/run_mean_std.py; numbers in mean_std.json.", ""]
tables = {}
for key, r in res.items():
    t, b, arm = key.split("|"); tables.setdefault(t, {}).setdefault(b, []).append((arm, r))
for t, benches in tables.items():
    md += [f"## table: {t}", ""]
    tex = ["\\begin{tabular}{llccc}", "\\toprule", "bench & arm & PSNR$_\\Omega$ (mean $\\pm$ std) & SSIM (mean $\\pm$ std) & $n$\\\\", "\\midrule"]
    for b, rows in benches.items():
        md += [f"### {b}", "", "| arm | PSNR_Ω mean ± std (ref) | median | SSIM mean ± std | n |", "|---|---|---|---|---|"]
        for arm, r in rows:
            if "error" in r: md.append(f"| {arm} | ERROR: {r['error']} | | | |"); continue
            ref = f" ({r['psnr_ref']:.2f})" if "psnr_ref" in r else ""
            ss = f"{r['ssim_mean']:.3f} ± {r['ssim_std']:.3f}" if "ssim_mean" in r else ""
            md.append(f"| {arm} | {r['psnr_mean']:.2f} ± {r['psnr_std']:.2f}{ref} | {r['psnr_median']:.2f} | {ss} | {r['n']} |")
            ss_tex = ss.replace("±", "$\\pm$"); arm_tex = arm.replace("_", " "); PM = "$\\pm$"; EOL = "\\\\"
            tex.append(f"{b} & {arm_tex} & {r['psnr_mean']:.2f} {PM} {r['psnr_std']:.2f} & {ss_tex} & {r['n']}{EOL}")
        md.append(""); tex.append("\\midrule")
    tex[-1] = "\\bottomrule"; tex.append("\\end{tabular}")
    try: (REPO / "paper/tables" / f"mean_std_{t}.tex").write_text("\n".join(tex) + "\n")
    except OSError as ex: print(f"[WARN] tex {t} not written: {ex}")
try: (OUT / "mean_std.md").write_text("\n".join(md) + "\n"); print("wrote", OUT / "mean_std.md")
except OSError as ex: print(f"[WARN] md not written: {ex}")
print("DONE")
