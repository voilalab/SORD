"""Ablation over the two declared inputs on the CelebA benches (user 2026-09-25: "make the ablation over the effect of mask
and noise mode"): (i) the corruption support Omega -- given exactly (updates projected over Omega) or not given (all-ones
mask, no projection); (ii) the contaminant model -- none (one target prior, ours), a matched contaminant DM in our n-step
(dmn arms), a Gaussian likelihood on Omega (DPS mu=0 / mu=n-bar oracle; DPS-inpaint = sigma->inf), or a second prior inside
the joint sampler (SGM/PiGDM: one CelebA prior in both blocks, one prior with the noise-block update dropped, two matched priors).
Per-image on-Omega PSNR (peak 1, clip [0,1], true support), mean +- std / worst, n=100 faces per bench, same 100 faces and
scoring as tab:faces / celeba_dps_cols (loader of paper/figs/qual/make_celeba_dps_fig.py).
Sources: experiments/ros/results/r5/<bench>/{min_nomask,dmn_exact,dmn_nomask}/c*/ *.npz (x_alt),
         experiments/ros/results/r5/<bench>/{sgm|sgm_free,sgmM,sgm_celebaN,sgmM_celebaN,sgm_x0n,sgmM_x0n}/c*.npz (x_A),
         experiments/extbench/results/{dpsg,dpsp}/<bench>/*.npz (DPS), paper ours/gt/mask via load_bench.
Run from the repo root:  python experiments/reviewer_audit/make_mask_noise_ablation_table.py
-> paper/tables/ablation_mask_noise.tex, experiments/reviewer_audit/results/ablation_mask_noise.md
"""
import sys, glob
from pathlib import Path
import numpy as np
sys.path.insert(0, "paper/figs/qual"); sys.path.insert(0, "experiments/reviewer_audit")
from make_celeba_dps_fig import load_bench, psnr

R5 = Path("experiments/ros/results/r5")
BENCH = [("mnist", "MNIST digit"), ("natural", "Natural patch"), ("cifar", "CIFAR-10 patch")]

def ours_arm(bench, tag, key="x_alt"):
    ds = sorted(glob.glob(str(R5 / bench / tag / "c*")), key=lambda s: int(Path(s).name[1:]))
    fs = [sorted(glob.glob(d + "/*.npz"))[0] for d in ds]
    return np.concatenate([np.load(f)[key] for f in fs]), np.concatenate([np.load(f)["x_A"] for f in fs])

def sgm_arm(bench, tag):
    fs = sorted(glob.glob(str(R5 / bench / tag / "c*.npz")), key=lambda s: int(Path(s).stem[1:]))
    return np.concatenate([np.load(f)["x_A"] for f in fs])

# (group, label, {no-mask arm, exact-mask arm}) ; arm = callable(bench, A) -> per-image estimate array or None
ROWS = [
    ("none (one target prior)", r"\methodmin{} (ours)",
     lambda b, A: ours_arm(b, "min_nomask")[0], lambda b, A: A["ours"]),
    ("matched contaminant DM in the $n$-step", r"\methodmin{} + contaminant DM",
     lambda b, A: ours_arm(b, "dmn_nomask")[0], lambda b, A: ours_arm(b, "dmn_exact")[0]),
    ("none on $\\Omega$ (DPS-inpaint, $\\sigma\\to\\infty$)", "DPS-inpaint, same prior",
     None, lambda b, A: A["dps_inp"]),
    ("Gaussian on $\\Omega$", "adaptive DPS, $\\mu=0$",
     None, lambda b, A: A["dps_mu0"]),
    ("Gaussian on $\\Omega$", "adaptive DPS, $\\mu=\\bar n_\\Omega$ (oracle)",
     None, lambda b, A: A["dps_mu"]),
    ("joint sampler, one prior in both blocks", "SGM/PiGDM, one prior",
     lambda b, A: sgm_arm(b, "sgm_celebaN"), lambda b, A: sgm_arm(b, "sgmM_celebaN")),
    ("joint sampler, one prior, no contaminant update", "SGM/PiGDM, one prior, $n$-block frozen",
     lambda b, A: sgm_arm(b, "sgm_x0n"), lambda b, A: sgm_arm(b, "sgmM_x0n")),
    ("joint sampler, second matched prior", "SGM/BASIS, two priors",
     lambda b, A: sgm_arm(b, "sgm_free" if b == "cifar" else "sgm"), lambda b, A: sgm_arm(b, "sgmM")),
]

def cell(v):
    return "--" if v is None else f"{v.mean():.2f} $\\pm$ {v.std(ddof=1):.2f} / {v.min():.2f}"

def main():
    A = {b: load_bench(b) for b, _ in BENCH}
    for b, _ in BENCH:   # alignment guard: the no-mask / dmn runs must hold the same 100 faces in the same order
        for tag in ("min_nomask", "dmn_exact", "dmn_nomask"):
            gt = ours_arm(b, tag)[1]; assert np.abs(gt - A[b]["gt"]).max() < 1e-5, (b, tag)
    vals = {}   # (row idx, bench, mask) -> per-image array
    for i, (grp, lab, f0, f1) in enumerate(ROWS):
        for b, _ in BENCH:
            for mk, f in (("none", f0), ("exact", f1)):
                if f is None: vals[(i, b, mk)] = None; continue
                est = f(b, A[b]); n = len(A[b]["gt"]); assert len(est) == n, (lab, b, mk, len(est))
                vals[(i, b, mk)] = np.array([psnr(est[j], A[b]["gt"][j], A[b]["M"][j]) for j in range(n)])
    inp = {b: np.array([psnr(A[b]["y"][j], A[b]["gt"][j], A[b]["M"][j]) for j in range(len(A[b]["gt"]))]) for b, _ in BENCH}
    # best per column (exact and no-mask separately) for bold
    best = {}
    for b, _ in BENCH:
        for mk in ("none", "exact"):
            cand = [(vals[(i, b, mk)].mean(), i) for i in range(len(ROWS)) if vals[(i, b, mk)] is not None]
            best[(b, mk)] = max(cand)[1]
    hdr = " & ".join([f"\\multicolumn{{2}}{{c}}{{{lab}}}" for _, lab in BENCH])
    L = ["% auto-generated by experiments/reviewer_audit/make_mask_noise_ablation_table.py (2026-09-25); on-Omega PSNR mean $\\pm$ std / worst, n=100",
         "\\begin{table*}[t]", "    \\centering", "    \\caption{",
         "    \\textbf{Effect of the support mask and of the contaminant model on the CelebA benches.}",
         "    On-$\\Omega$ PSNR (dB), mean $\\pm$ std / worst over $n{=}100$ faces per bench, same images and scoring as \\cref{tab:faces}.",
         "    \\emph{Mask}: \\emph{none} = the method is run with an all-ones support (no projection of updates over $\\Omega$); \\emph{exact} = the true support is given and every update is projected onto it (DPS needs the mask and has no mask-free form).",
         "    \\emph{Contaminant model}: ours uses only the target prior and reads $n$ through it; the second row swaps in a diffusion model of the contaminant class inside the $n$-step (MNIST-RGB / natural-patch / CIFAR-10 prior); DPS models $n$ on $\\Omega$ as Gaussian ($\\mu=0$, or the per-image oracle mean $\\bar n_\\Omega$) or discards $y_\\Omega$ (inpaint); the joint sampler SGM/PiGDM is run with the CelebA prior in both blocks (one prior), with that noise block frozen, or with a second prior matched to the contaminant class.",
         "    Bold: best per column.", "    }", "    \\label{tab:ablation_mask_noise}", "    \\small", "    \\setlength{\\tabcolsep}{3pt}",
         "    \\resizebox{\\textwidth}{!}{", "    \\begin{tabular}{@{}llcccccc@{}}", "        \\toprule",
         f"        \\textbf{{Contaminant model}} & \\textbf{{Method}} & {hdr} \\\\",
         "        \\cmidrule(lr){3-4} \\cmidrule(lr){5-6} \\cmidrule(lr){7-8}",
         "        & & " + " & ".join(["no mask & exact mask"] * 3) + " \\\\", "        \\midrule",
         "        -- & input $y$ & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{cell(inp[b])}}}" for b, _ in BENCH) + " \\\\", "        \\midrule"]
    md = ["# Mask x contaminant-model ablation on CelebA (on-Omega PSNR mean ± std / worst, n=100)", "",
          "| contaminant model | method | " + " | ".join(f"{lab} no mask | {lab} exact" for _, lab in BENCH) + " |", "|---|---|" + "---|" * 6,
          "| -- | input y | " + " | ".join(f"{inp[b].mean():.2f} ± {inp[b].std(ddof=1):.2f} / {inp[b].min():.2f} | same" for b, _ in BENCH) + " |"]
    for i, (grp, lab, _, _) in enumerate(ROWS):
        cs = []
        for b, _ in BENCH:
            for mk in ("none", "exact"):
                c = cell(vals[(i, b, mk)])
                if best[(b, mk)] == i: c = c.replace(" / ", "} / ", 1).replace(f"{vals[(i,b,mk)].mean():.2f}", f"\\textbf{{{vals[(i,b,mk)].mean():.2f}", 1)
                cs.append(c)
        L.append(f"        {grp} & {lab} & " + " & ".join(cs) + " \\\\")
        md.append(f"| {grp} | {lab} | " + " | ".join(cell(vals[(i, b, mk)]).replace('$\\pm$', '±') for b, _ in BENCH for mk in ('none', 'exact')) + " |")
        if i in (1, 4): L.append("        \\midrule")
    L += ["        \\bottomrule", "    \\end{tabular}}", "\\end{table*}"]
    Path("paper/tables/ablation_mask_noise.tex").write_text("\n".join(L) + "\n")
    Path("experiments/reviewer_audit/results/ablation_mask_noise.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))

if __name__ == "__main__":
    main()
